// Keep the supplied mentor options read-only; rebuild the displayed catalog.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const context = vm.createContext({ window: {} });
vm.runInContext(fs.readFileSync(path.join(__dirname, '../../reference_notes/mentor-options.js'), 'utf8'), context);
const options = context.window.LT_OPTIONS;
const pairs = context.window.LT_DOMAIN_PAIRS;
const domainsFor = category => /家庭/.test(category) ? ['家庭','人际']
  : /学习/.test(category) ? ['学业']
  : /健康/.test(category) ? ['健康','生活转变']
  : /新环境/.test(category) ? ['生活转变','个人成长']
  : /兴趣/.test(category) ? ['个人成长']
  : /丧失/.test(category) ? ['人际','生活转变'] : ['人际'];
const items = [];
for (const [side, valence] of [['neg', -1], ['pos', 1]]) {
  let index = 0;
  options[side].categories.forEach((category, categoryIndex) => {
    options[side].items[category].forEach(item => items.push({
      id: `mentor_${side}_${String(++index).padStart(2,'0')}`,
      label: item.t, theme: category, domain: category, valence,
      domains: domainsFor(category), source_scope: 'general',
      source_catalog: 'mentor-options-v2.1', category_index: categoryIndex,
      group_index: pairs.findIndex(pair => pair[side] === category),
      group_title: pairs.find(pair => pair[side] === category).title,
      aslec_bridge: item.a, hint: '',
    }));
  });
}
// Original severity weights and automatic attribution codes are NOT participant
// answers or validated sports norms, and are not copied into active events.
const output = `/* Generated by adapt-mentor-catalog.cjs from the supplied mentor options v2.1.
 * Original wording, categories and within-category order; sports added separately.
 */
(function(root) {
  const items = ${JSON.stringify(items, null, 2)};
  if (typeof module !== 'undefined' && module.exports) module.exports = items;
  else root.LifeEventCatalog = items;
})(typeof window !== 'undefined' ? window : globalThis);
`;
fs.writeFileSync(path.join(__dirname,'life-event-catalog.js'), output);
console.log(`Mentor catalog rebuilt: ${items.filter(e=>e.valence<0).length} negative + ${items.filter(e=>e.valence>0).length} positive prompts.`);
